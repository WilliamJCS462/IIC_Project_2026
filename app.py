#load the yaml which might not exist yet
def load_metrics():
    metrics_path = base_dir / "tests" / "metrics.yaml"
    if metrics_path.exists():
        with open(metrics_path, "r") as file:
            metrics = yaml.safe_load(file) or {}
    else:
        metrics = {}
    if "accuracy" in metrics:
        accuracy_message = f"Estimated Accuracy: {int(round(metrics['accuracy'], 2) * 100)}%"
    else:
        accuracy_message = f"Estimated Accuracy: Untested"
    return accuracy_message

@st.dialog("Data")
def data_popup(df, title, extra: str=""):
    st.subheader(title)
    if (df is not None) and not isinstance(df, str):
        st.dataframe(df)
    else:
        st.markdown("No data")
    if extra != "":
        st.code(extra, language="sql")

