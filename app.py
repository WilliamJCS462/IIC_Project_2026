import streamlit as st
import os
import yaml
from dotenv import load_dotenv, dotenv_values
from pathlib import Path
from graph.graph import run_graph
from database.database import database_init
from utils.errors import get_error_code
from tests.tests import run_accuracy_tests

base_dir = Path(__file__).resolve().parent
load_dotenv()

#start database
database_init()

#import styles
styles = Path("utils/styles.css")
st.markdown(f"<style>{styles.read_text()}</style>", unsafe_allow_html=True)

#load the yaml which might not exist yet
def load_metrics():
    metrics_path = base_dir / "tests" / "metrics.yaml"
    if metrics_path.exists():
        with open(metrics_path, "r") as file:
            metrics = yaml.safe_load(file) or {}
    else:
        metrics = {}
    if "accuracy" in metrics:
        accuracy_message = f"Estimated Accuracy: {int(round(metrics['accuracy'], 2) * 100)}%"
    else:
        accuracy_message = f"Estimated Accuracy: Untested"
    return accuracy_message

st.set_page_config(
    page_title="SQL Assistant",
    page_icon="👾",
    layout="wide"
)

#load improvements config
improvements_path = base_dir / "config" / "improvements.yaml"

default_config = {
        "accuracy_scoring": False,
        "complexity_scoring" : False
        }

if improvements_path.exists():
    with open(improvements_path, "r") as file:
        st.session_state.improvements = yaml.safe_load(file) or default_config
else:
    #set default config to false
    st.session_state.improvements = default_config

    #create config file if not found
    with open(improvements_path, "w") as file:
        yaml.safe_dump(st.session_state.improvements, file)

with st.sidebar:
    st.header("Improvement Features")
    #accuracy scoring
    if st.toggle(label="Estimated Accuracy Scoring", key="accuracy_scoring", value=st.session_state.improvements["accuracy_scoring"], help="Estimated accuracy of the chatbot. Based on a set of human generated prompts and answers"):
        st.session_state.improvements["accuracy_scoring"] = True
    else:
        st.session_state.improvements["accuracy_scoring"] = False
    #update config file
    with open(improvements_path, "w") as file:
        yaml.safe_dump(st.session_state.improvements, file)

    #complexity scoring
    if st.toggle(label="Query Complexity Scoring", key="complexity_scoring", value=st.session_state.improvements["complexity_scoring"], help="Shows the complexity of the SQL generated by the assistant to help answer the question. The higher the complexity, the higher the risk."):
        st.session_state.improvements["complexity_scoring"] = True
    else:
        st.session_state.improvements["complexity_scoring"] = False
    #update config file
    with open(improvements_path, "w") as file:
        yaml.safe_dump(st.session_state.improvements, file)

#conditional css styling to hide elements
if not st.session_state.improvements["accuracy_scoring"]:
    st.markdown("""
        <style>

        .st-key-accuracy_score, .st-key-accuracy_button {
            display: None;
        }
    """, unsafe_allow_html=True)

if not st.session_state.improvements["complexity_scoring"]:
    st.markdown("""
        <style>

        .stChatMessage:has([aria-label="Chat message from assistant"]) > :nth-child(2) :nth-child(3) {
            display: None;
        }
    """, unsafe_allow_html=True)

with st.container(key="chatbot"):

    with st.container(key="title_bar"):
        with st.container(key="chatbot_pfp"):
            st.markdown("👾")

        with st.container(key="title_caption"):
            st.title("SQL Assistant")
            st.caption("AI Powered SQL Assistant")

        if st.button(label="Calculate Accuracy", key="accuracy_button"):
            st.session_state.calc_accuracy = True #delay button function for streamlit ordering :(

        with st.container(key="accuracy_score", width="content"):
            accuracy_placeholder = st.empty() #switches between progress bar and content score

            if st.session_state.get("calc_accuracy", False):
                test_progress = accuracy_placeholder.progress(0, text="Starting tests...") #progress bar, inserted into the accuracy placeholder

                #create a function to use as a callback
                def update_progress(current, total):
                    test_progress.progress(current / total, text="Running tests...")

                run_accuracy_tests(update_progress) #actually runs the tests, updates the progress bar internally

                st.session_state.calc_accuracy = False #reset button

                accuracy_placeholder.markdown(load_metrics()) #when finished load

            else:
                accuracy_placeholder.markdown(load_metrics()) #be default load

    #being slightly clever here. Inserting into messsages container both before and after prompt as this needs to be outside messages so it pins to the bottom
    messages = st.container(key="messages", height=300, border=None)

    with messages:
        if "messages" not in st.session_state:
            st.session_state.messages = []

        for message in st.session_state.messages:
            with st.chat_message(message["role"]):
                #if complexity scoring:
                    with st.container():
                        st.markdown(message["content"])
                        st.markdown("") #used to do css referencing, here acts as a placeholder for the spinner message
                        st.markdown(message["complexity_scoring"])

    with st.container(key="prompt_bar"):
        prompt = st.chat_input("Ask the assistant a question...")

    if prompt:
        st.session_state.messages.append({
            "role": "user",
            "content": prompt,
            "complexity_scoring": "" #user messages dont have complexity scoring but we want message objects to be as similar as possible hence a placeholder here
        })

        with messages:
            with st.chat_message("user", avatar=":material/account_circle:"):
                st.markdown(prompt)

            with st.chat_message("assistant", avatar=":material/robot_2:"):
                response_placeholder = st.empty() #I don't know why this works but found this solution to duplicate chat messages appearing under the assistant
                with response_placeholder.container():
                    with st.spinner("Thinking..."):
                        try:
                            response, improvements = run_graph(prompt)
                        except Exception as e:
                            response = f"ERROR - Error Codes: GRAPH_RUN_FAILURE, {get_error_code(e)}"
                            #default improvements
                            improvements = {
                                "complexity_score": 0
                            }

                    response_container = st.container()
                    with response_container:
                        st.markdown(response)
                        st.markdown("") #used to do css referencing, here acts as a placeholder for the spinner message
                        st.markdown(f"Query Complexity: {improvements['complexity_score']}%")


        st.session_state.messages.append({
            "role": "assistant",
            "content": response,
            "complexity_scoring": f"Query Complexity: {improvements['complexity_score']}%"
        })
