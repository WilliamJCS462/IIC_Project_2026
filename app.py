with st.container(key="chatbot"):

    with st.container(key="title_bar"):
        with st.container(key="chatbot_pfp"):
            st.markdown("👾")

        with st.container(key="title_caption"):
            st.title("SQL Assistant")
            st.caption("AI Powered SQL Assistant")

        if st.button(label="Calculate Accuracy", key="accuracy_button"):
            st.session_state.calc_accuracy = True #delay button function for streamlit ordering :(

        with st.container(key="accuracy_score", width="content"):
            accuracy_placeholder = st.empty() #switches between progress bar and content score

            if st.session_state.get("calc_accuracy", False):
                test_progress = accuracy_placeholder.progress(0, text="Starting tests...") #progress bar, inserted into the accuracy placeholder

                #create a function to use as a callback
                def update_progress(current, total):
                    test_progress.progress(current / total, text="Running tests...")

                run_accuracy_tests(update_progress) #actually runs the tests, updates the progress bar internally

                st.session_state.calc_accuracy = False #reset button

                accuracy_placeholder.markdown(load_metrics()) #when finished load

            else:
                accuracy_placeholder.markdown(load_metrics()) #be default load

    #being slightly clever here. Inserting into messsages container both before and after prompt as this needs to be outside messages so it pins to the bottom
    messages = st.container(key="messages", height=300, border=None)

    with messages:
        if "messages" not in st.session_state:
            st.session_state.messages = []

        for i, message in enumerate(st.session_state.messages):
            with st.chat_message(message["role"]):
                    with st.container():
                        #puts the info button next to the main response
                        if message["role"] == "assistant":
                            with st.container():
                                col1, col2 = st.columns([20,1])
                                with col1:
                                    st.markdown(message["content"])
                                with col2:
                                    with st.popover("ℹ️"):
                                        st.write(message["reasoning"])
                        else:
                            st.markdown(message["content"])
                        st.markdown("") #used to do css referencing, here acts as a placeholder for the spinner message
                        expanded_context_notification = ""
                        if message["expanded_context"] != "":
                            expanded_context_notification = "*This answer was generated with expanded context"
                        st.markdown(expanded_context_notification)
                        st.markdown(message["auditing_message"])
                        st.markdown(message["complexity_scoring"])
                        st.markdown(message["sql_query"])
                        if message["role"] == "assistant":
                            if st.button("View Data", key=f"data_button_{i // 2}"): #we will use tertiary buttons for display
                                data_popup(df=message["sql_data"], title="Query Data")
                            if st.button("View Supporting Data", key=f"drill_down_button_{i // 2}"): #we will use tertiary buttons for display
                                data_popup(df=message["drill_down_data"], title="Supporting Data", extra=message["drill_down_sql"])

    with st.container(key="prompt_bar"):
        prompt = st.chat_input("Ask the assistant a question...")

    if prompt:
        st.session_state.messages.append({
            "role": "user",
            "content": prompt,
            #user messages dont have improvements but its helpful to include them as blanks here so that all messages are the same
            "complexity_scoring": "",
            "sql_query": "",
            "sql_data": "",
            "reasoning": "",
            "drill_down_data": "",
            "drill_down_sql": "",
            "expanded_context": "",
            "auditing_message": "",
        })

        with messages:
            with st.chat_message("user", avatar=":material/account_circle:"):
                st.markdown(prompt)

            with st.chat_message("assistant", avatar=":material/robot_2:"):
                response_placeholder = st.empty() #I don't know why this works but found this solution to duplicate chat messages appearing under the assistant
                with response_placeholder.container():
                    try:
                        if not st.session_state.improvements["logging"]:
                            with st.spinner("Thinking..."):
                                response, improvements = run_graph(prompt)
                        else:
                            process_stage = st.empty()
                            completed_stages = ["Initialising"]
                            def update_stage(stage):
                                if stage not in completed_stages and stage is not None:
                                    completed_stages.append(stage)
                                if stage is not None:
                                    text = "  \n".join(f"✅ {n}" for n in completed_stages[:-1]) + f"  \n🔄 {completed_stages[-1]}"
                                    process_stage.text(text)
                                        
                                else:
                                    process_stage.text("  \n".join(f"✅ {n}" for n in completed_stages)) #if stage name is None, graph has finished running
                            response, improvements = run_graph(prompt, status_callback=update_stage)
                    except Exception as e:
                        response = f"ERROR - Error Codes: GRAPH_RUN_FAILURE, {get_error_code(e)}"
                        #default improvements / deafult trust measures from graph
                        improvements = {
                            "complexity_score": 0,
                            "reasoning": "",
                            "sql_query": "",
                            "sql_data": None,
                            "drill_down_data": None,
                            "drill_down_sql": "",
                            "expanded_context": "",
                            "auditing_status": "",
                            "auditing_issues": [],
                            "auditing_count": 0
                        }

        auditing_message = ""
        if improvements["auditing_status"] == "pass" and improvements["auditing_count"] > 0:
            auditing_message = "*This response has been audited"
        elif improvements["auditing_status"] == "sql_fail":
            auditing_message = "*WARNING: This response failed SQL auditing. It may contain errors"
        elif improvements["auditing_status"] == "response_fail":
            auditing_message = "*WARNING: This response failed Response auditing. It may contain errors"

        st.session_state.messages.append({
            "role": "assistant",
            "content": response,
            "complexity_scoring": f"Query Complexity: {improvements['complexity_score']}%",
            "sql_query": f"SQL: {improvements['sql_query']}",
            "sql_data": improvements["sql_data"],
            "reasoning": improvements["reasoning"],
            "drill_down_data": improvements["drill_down_data"],
            "drill_down_sql": improvements["drill_down_sql"],
            "expanded_context": improvements["expanded_context"],
            "auditing_message": auditing_message
        })

        time.sleep(0.5) #slight delay for logging to show
        st.rerun() #reload the page so message goes into session state
